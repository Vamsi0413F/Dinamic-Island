import Foundation
import AppKit
import Vision

@MainActor
public final class ClipboardService: ObservableObject {
    public static let shared = ClipboardService()
    
    @Published public private(set) var items: [ClipboardItem] = []
    @Published public var searchText: String = ""
    @Published public var isMonitoringPaused: Bool = false
    
    private var lastChangeCount: Int = NSPasteboard.general.changeCount
    private var timer: Timer?
    
    public init() {
        startMonitoring()
    }
    
    public func startMonitoring() {
        timer?.invalidate()
        timer = Timer.scheduledTimer(withTimeInterval: 0.75, repeats: true) { [weak self] _ in
            Task { @MainActor [weak self] in
                self?.checkPasteboard()
            }
        }
    }
    
    public func checkPasteboard() {
        guard !isMonitoringPaused else { return }
        guard SettingsStore.shared.clipboardMonitoringEnabled else { return }
        
        let pasteboard = NSPasteboard.general
        let currentCount = pasteboard.changeCount
        guard currentCount != lastChangeCount else { return }
        lastChangeCount = currentCount
        
        // Check for transient / concealed types (password managers like 1Password, Bitwarden mark types)
        let types = pasteboard.types ?? []
        for type in types {
            if type.rawValue.contains("Concealed") ||
               type.rawValue.contains("Transient") ||
               type.rawValue.contains("AutoGenerated") {
                return
            }
        }
        
        if let text = pasteboard.string(forType: .string) {
            let trimmed = text.trimmingCharacters(in: .whitespacesAndNewlines)
            guard !trimmed.isEmpty else { return }
            
            // Check for obvious sensitive content
            let isSensitive = detectSensitive(text: trimmed)
            
            // Remove existing duplicate if not pinned
            items.removeAll { $0.text == trimmed && !$0.isPinned }
            
            let newItem = ClipboardItem(
                text: trimmed,
                imageHash: nil,
                date: Date(),
                isPinned: false,
                isSensitive: isSensitive
            )
            items.insert(newItem, at: 0)
            
            // Limit to configured max
            let maxCount = SettingsStore.shared.clipboardMaxItems
            if items.count > maxCount {
                let unpinned = items.filter { !$0.isPinned }
                if unpinned.count > maxCount {
                    if let lastUnpinnedIndex = items.lastIndex(where: { !$0.isPinned }) {
                        items.remove(at: lastUnpinnedIndex)
                    }
                }
            }
        }
    }
    
    private func detectSensitive(text: String) -> Bool {
        // High-entropy token, private key header, or password-like pattern
        if text.contains("-----BEGIN") && text.contains("PRIVATE KEY-----") { return true }
        if text.hasPrefix("ghp_") || text.hasPrefix("sk-") || text.hasPrefix("xoxb-") { return true }
        return false
    }
    
    public var filteredItems: [ClipboardItem] {
        if searchText.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            return items
        }
        let query = searchText.lowercased()
        return items.filter { ($0.text ?? "").lowercased().contains(query) }
    }
    
    public func copyToPasteboard(item: ClipboardItem) {
        guard let text = item.text else { return }
        let pasteboard = NSPasteboard.general
        pasteboard.clearContents()
        pasteboard.setString(text, forType: .string)
        self.lastChangeCount = pasteboard.changeCount
    }
    
    public func togglePin(item: ClipboardItem) {
        if let idx = items.firstIndex(where: { $0.id == item.id }) {
            items[idx].isPinned.toggle()
        }
    }
    
    public func removeItem(item: ClipboardItem) {
        items.removeAll { $0.id == item.id }
    }
    
    public func clearUnpinned() {
        items.removeAll { !$0.isPinned }
    }
    
    public func performOCR(on image: NSImage) async -> String? {
        guard let cgImage = image.cgImage(forProposedRect: nil, context: nil, hints: nil) else {
            return nil
        }
        
        return await withCheckedContinuation { continuation in
            let request = VNRecognizeTextRequest { request, error in
                guard error == nil,
                      let observations = request.results as? [VNRecognizedTextObservation] else {
                    continuation.resume(returning: nil)
                    return
                }
                let recognizedStrings = observations.compactMap { $0.topCandidates(1).first?.string }
                let combined = recognizedStrings.joined(separator: "\n")
                continuation.resume(returning: combined.isEmpty ? nil : combined)
            }
            request.recognitionLevel = .accurate
            request.usesLanguageCorrection = true
            
            let handler = VNImageRequestHandler(cgImage: cgImage, options: [:])
            do {
                try handler.perform([request])
            } catch {
                continuation.resume(returning: nil)
            }
        }
    }
    
    isolated deinit {
        timer?.invalidate()
    }
}
